"""Ports for account and library aggregates and their read models."""

from __future__ import annotations

from typing import Protocol

from app.domain.workspace import Account, LibraryDocument, ModelPreset


class AccountRepo(Protocol):
    def get(self, account_id: int) -> Account | None: ...
    def by_email(self, email: str) -> Account | None: ...
    def save(self, account: Account) -> Account: ...
    def list_with_usage(self) -> list[dict]: ...
    def providers(self, user_id: int) -> list[ModelPreset]: ...
    def provider(self, user_id: int, provider_id: int) -> ModelPreset: ...
    def save_provider(self, provider: ModelPreset) -> ModelPreset: ...
    def delete_provider(self, provider: ModelPreset) -> None: ...
    def usage(self, user_id: int) -> dict: ...


class DocumentRepo(Protocol):
    def list(self, user_id: int) -> list[LibraryDocument]: ...
    def owned(self, user_id: int, document_id: int) -> LibraryDocument: ...
    def save(self, document: LibraryDocument) -> LibraryDocument: ...
    def replace_chunks(self, document_id: int, chunks: list[str]) -> None: ...
    def delete(self, document: LibraryDocument) -> None: ...
    def search(self, user_id: int, query: str) -> list[dict]: ...
