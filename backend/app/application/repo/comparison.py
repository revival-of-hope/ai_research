"""Repository interface for comparison snapshots and selected source content."""

from __future__ import annotations

from typing import Protocol

from app.domain.research import ProviderConfig


class ComparisonRepository(Protocol):
    def prepare(self, user_id: int, paper_id: int, run_id: int, provider_id: int, metric: str) -> tuple[ProviderConfig, dict, dict]: ...
    def list(self, user_id: int) -> list[dict]: ...
    def get(self, user_id: int, comparison_id: int) -> dict: ...
    def evidence(self, user_id: int, comparison_id: int, side: str, key: str) -> dict: ...
    def source_chunks(
        self, user_id: int, comparison_id: int, side: str, query: str | None,
    ) -> list[dict]: ...
    def validate_source_reference(
        self, user_id: int, comparison_id: int, side: str,
        chunk_id: int, excerpt: str,
    ) -> None: ...
    def get_for_update(self, user_id: int, comparison_id: int) -> dict: ...
    def create(self, user_id: int, paper: dict, run: dict, provider_id: int, metric: str, fields: list[dict]) -> dict: ...
    def update(self, user_id: int, comparison_id: int, fields: list[dict], status: str) -> dict: ...
